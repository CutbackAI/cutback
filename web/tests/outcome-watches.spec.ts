import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";

test("finite observation approval, lost response, history and read-only access", async ({ page }) => {
  test.skip(process.env.CUTBACK_WATCH_SAMPLE !== "true", "Requires owned observation fixture");
  test.setTimeout(90000);
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  async function connect(key: string) {
    await page.goto("/dashboard/?project=" + process.env.CUTBACK_UI_PROJECT);
    await page.getByLabel("Control API key").fill(key);
    await page.getByRole("button", { name: "Connect to this collector", exact: true }).click();
    await page.getByRole("button", { name: "Task economics", exact: true }).click();
  }
  await connect(process.env.CUTBACK_UI_KEY!);
  const region = page.getByRole("region", { name: "Automatic change observations", exact: true });
  const seeded = region.getByRole("article").filter({ hasText: "owned-change-followup" });
  await seeded.getByRole("button", { name: /Inspect observation history/ }).click();
  const history = page.getByRole("region", { name: "Automatic observation history" });
  await expect(history).toContainText("50.0%");
  await expect(history).toContainText("Review a possible outcome regression");
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  await history.screenshot({ path: "../artifacts/outcome-watch-history-desktop.png" });
  await region.getByText("Prepare an automatic observation policy", { exact: true }).click();
  const form = region.getByRole("form", { name: "Prepare automatic change observations" });
  await form.getByLabel("Observation policy name", { exact: true }).fill("browser-owned-followup");
  const baseline = form.getByRole("combobox", { name: /^Observation baseline/ });
  const reference = baseline.locator("option").filter({ hasText: "owned-reference" });
  await expect(reference).toHaveCount(1);
  await baseline.selectOption((await reference.getAttribute("value"))!);
  await form.getByRole("combobox", { name: /^Observed source change/ }).selectOption({ index: 1 });
  await form.getByLabel("Candidate application release", { exact: true }).fill("browser-candidate");
  await form.getByLabel(/I attest that this source change belongs/).check();
  const posted: string[] = [];
  await page.route(/\/outcome-watches\/draft\?/, async (route) => {
    posted.push(route.request().postDataJSON().watch_id);
    const response = await route.fetch();
    if (posted.length === 1) await route.abort("failed");
    else await route.fulfill({ response });
  });
  await form.getByRole("button", { name: "Freeze observation policy" }).click();
  await expect(form.getByRole("alert")).toBeVisible();
  await form.getByRole("button", { name: "Freeze observation policy" }).click();
  const created = region.getByRole("article").filter({ hasText: "browser-owned-followup" });
  await expect(created).toContainText("PENDING · release browser-candidate");
  expect(posted).toHaveLength(2);
  expect(posted[0]).toBe(posted[1]);
  await expect(region.getByRole("article")).toHaveCount(2);
  await created.getByText("Review the frozen policy", { exact: true }).click();
  await expect(created).toContainText("Approval SHA-256:");
  await created.getByLabel(/Policy approval reference/).fill("owned-browser-review");
  await created.getByRole("button", { name: "Approve this observation policy" }).click();
  await expect(created).toContainText("APPROVED");
  await created.getByRole("button", { name: /Pause policy/ }).click();
  await expect(created).toContainText("PAUSED");
  await created.getByRole("button", { name: /Resume policy/ }).click();
  await expect(created).toContainText("APPROVED");
  await expect(created).toContainText("0 of 30 checks used");
  await page.setViewportSize({ width: 390, height: 844 });
  await history.screenshot({ path: "../artifacts/outcome-watch-history-mobile.png" });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  await connect(process.env.CUTBACK_UI_VIEWER!);
  await expect(region.getByRole("article")).toHaveCount(2);
  await expect(region.getByText("Prepare an automatic observation policy", { exact: true })).toHaveCount(0);
  await expect(region.getByRole("button", { name: /Pause policy|Resume policy|Approve this/ })).toHaveCount(0);
  await seeded.getByRole("button", { name: /Inspect observation history/ }).click();
  await expect(history).toContainText("50.0%");
  expect(errors).toEqual([]);
});
