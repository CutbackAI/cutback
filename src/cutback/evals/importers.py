"""Versioned offline projections. Never executes evaluator/config/provider code."""

import hashlib
import json
from dataclasses import dataclass
from decimal import Decimal
from pathlib import Path
from typing import Literal, cast

from pydantic import TypeAdapter, ValidationError

from cutback.core.traces import SpanID, TraceID
from cutback.evals.datasets import Case, digest

ImportProfile = Literal[
    "cutback-jsonl.v1", "openinference-otlp-json.v1", "promptfoo-0.125.1-results.v3"
]
PROFILES = ("cutback-jsonl.v1", "openinference-otlp-json.v1", "promptfoo-0.125.1-results.v3")
MAX_BYTES = 1048576


class SourceImportError(ValueError):
    """A fixed, content-free diagnostic generated by this adapter."""


MAPPINGS = {
    "cutback-jsonl.v1": {
        "input": "input",
        "declared_expectation": "gold (unreviewed)",
        "historical_reference": "reference",
        "group": "group",
    },
    "openinference-otlp-json.v1": {
        "input": "input.value.stringValue",
        "declared_expectation": "none",
        "historical_reference": "output.value.stringValue",
        "group": "session.id (hashed)",
    },
    "promptfoo-0.125.1-results.v3": {
        "input": "testCase.vars.input",
        "declared_expectation": "one literal equals assertion (unreviewed)",
        "historical_reference": "response.output",
        "checks": "source success/score/failureReason (externally asserted)",
    },
}


def import_profile(value: str) -> ImportProfile:
    if value not in PROFILES:
        raise SourceImportError("IMPORT_PROFILE_UNSUPPORTED")
    return cast(ImportProfile, value)


def _ordinary_json(value):
    if isinstance(value, Decimal):
        converted = float(value)
        if not value.is_finite() or Decimal(str(converted)) != value:
            raise SourceImportError("STRUCTURED_JSON_NUMBER_CANNOT_BE_PRESERVED")
        return converted
    if isinstance(value, dict):
        return {key: _ordinary_json(item) for key, item in value.items()}
    if isinstance(value, list):
        return [_ordinary_json(item) for item in value]
    return value


def _unique(pairs):
    value = {}
    for key, item in pairs:
        if key in value:
            raise SourceImportError("DUPLICATE_IMPORT_FIELD")
        value[key] = item
    return value


def _nonfinite(_):
    raise SourceImportError("NONFINITE_IMPORT_NUMBER")


def _json(value):
    try:
        data = json.loads(
            value, object_pairs_hook=_unique, parse_float=Decimal, parse_constant=_nonfinite
        )
    except (ValueError, RecursionError):
        raise SourceImportError("MALFORMED_OR_DUPLICATE_IMPORT_JSON") from None
    pending = [(data, 0)]
    while pending:
        item, depth = pending.pop()
        if depth > 20:
            raise SourceImportError("IMPORT_NESTING_EXCEEDS_TWENTY")
        if isinstance(item, (dict, list)):
            pending.extend(
                (v, depth + 1) for v in (item.values() if isinstance(item, dict) else item)
            )
    return data


@dataclass
class PreparedImport:
    profile: str
    source_sha256: str
    cases: list[Case]
    rejected: list[dict]
    source_rows: int
    projected_fields: int
    assertions: list[dict]

    def preview(self):
        """No examples, gold, outputs, reasons, config secrets or private field names."""
        return {
            "profile": self.profile,
            "mapping": MAPPINGS[self.profile],
            "source_sha256": self.source_sha256,
            "source_rows": self.source_rows,
            "accepted": len(self.cases),
            "rejected": len(self.rejected),
            "rejections": self.rejected[:100],
            "rejections_truncated": len(self.rejected) > 100,
            "projected_unmapped_fields": self.projected_fields,
            "case_fingerprints": [digest(c.model_dump(mode="json")) for c in self.cases[:25]],
            "case_fingerprints_truncated": len(self.cases) > 25,
            "literal_expectations": sum(c.gold is not None for c in self.cases),
            "historical_references": sum(c.reference is not None for c in self.cases),
            "source_asserted_checks": len(self.assertions),
            "independent_labels": False,
            "semantic_quality": "NOT_VERIFIED",
            "content_uploaded": False,
            "provider_calls": 0,
            "next_action": "review_mapping_rejections_and_rights_before_encrypted_import",
        }


def _attributes(values):
    if not isinstance(values, list) or len(values) > 64:
        raise SourceImportError("ATTRIBUTE_LIST_INVALID")
    result = {}
    for item in values:
        if (
            not isinstance(item, dict)
            or not isinstance(item.get("key"), str)
            or item["key"] in result
        ):
            raise SourceImportError("ATTRIBUTE_IDENTITY_INVALID")
        value = item.get("value")
        if not isinstance(value, dict) or len(value) != 1:
            raise SourceImportError("ATTRIBUTE_VALUE_INVALID")
        result[item["key"]] = value
    return result


def _openinference(row):
    if not isinstance(row, dict):
        raise SourceImportError("SPAN_ROW_REQUIRED")
    trace = TypeAdapter(TraceID).validate_python(row.get("traceId"))
    span = TypeAdapter(SpanID).validate_python(row.get("spanId"))
    if not int(trace, 16) or not int(span, 16):
        raise SourceImportError("NONZERO_SPAN_IDENTITIES_REQUIRED")
    attrs = _attributes(row.get("attributes", []))
    text, reference = (
        attrs.get("input.value", {}).get("stringValue"),
        attrs.get("output.value", {}).get("stringValue"),
    )
    if not isinstance(text, str) or not text:
        raise SourceImportError("EXPLICIT_STRING_INPUT_REQUIRED")
    if reference is not None and not isinstance(reference, str):
        raise SourceImportError("STRING_REFERENCE_REQUIRED")
    session = attrs.get("session.id", {}).get("stringValue")
    case = Case(
        id="oi:" + trace + ":" + span,
        input=text,
        reference=reference,
        group="session:" + digest(session) if isinstance(session, str) else None,
    )
    return case, max(0, len(attrs) - 3), None


def _promptfoo(row):
    if not isinstance(row, dict):
        raise SourceImportError("RESULT_ROW_REQUIRED")
    test = row.get("testCase")
    if not isinstance(test, dict) or not isinstance(test.get("vars"), dict):
        raise SourceImportError("EXPLICIT_TEST_CASE_VARIABLES_REQUIRED")
    text = test["vars"].get("input")
    if not isinstance(text, str) or not text:
        raise SourceImportError("EXPLICIT_STRING_INPUT_REQUIRED")
    declared = test.get("assert", [])
    if not isinstance(declared, list) or len(declared) > 100:
        raise SourceImportError("ASSERTION_LIST_INVALID")
    gold = None
    if len(declared) == 1 and isinstance(declared[0], dict) and declared[0].get("type") == "equals":
        gold = _ordinary_json(declared[0].get("value"))
        if not isinstance(gold, (str, list, dict)):
            raise SourceImportError("LITERAL_EXPECTATION_SHAPE_UNSUPPORTED")
    response = row.get("response", {})
    if not isinstance(response, dict):
        raise SourceImportError("RESPONSE_SHAPE_INVALID")
    reference = response.get("output")
    if reference is not None and not isinstance(reference, str):
        raise SourceImportError("STRING_REFERENCE_REQUIRED")
    identifier = (
        "pf:" + digest([row.get("testIdx"), row.get("promptIdx"), row.get("id"), text])[:48]
    )
    case = Case(
        id=identifier, input=text, gold=gold, reference=reference, group="pf-test:" + digest(text)
    )
    success, score = row.get("success"), row.get("score")
    asserted = None
    failure = row.get("failureReason")
    if failure is not None and (type(failure) is not int or failure not in {0, 1, 2}):
        raise SourceImportError("EXTERNAL_FAILURE_KIND_INVALID")
    if failure == 2 or response.get("error") is not None:
        asserted = {
            "case_id": case.id,
            "outcome": "error",
            "score": None,
            "error_code": "SOURCE_EXECUTION_ERROR",
            "evidence": "externally_asserted",
            "evaluator": "promptfoo",
            "profile": "promptfoo-0.125.1-results.v3",
        }
    elif type(success) is bool:
        if (
            not isinstance(score, (int, Decimal))
            or isinstance(score, bool)
            or not Decimal(score).is_finite()
            or abs(Decimal(score)) > Decimal("1e20")
        ):
            raise SourceImportError("EXTERNAL_SCORE_INVALID")
        asserted = {
            "case_id": case.id,
            "outcome": "passed" if success else "failed",
            "score": str(score),
            "evidence": "externally_asserted",
            "evaluator": "promptfoo",
            "profile": "promptfoo-0.125.1-results.v3",
        }
    ignored_assertions = len(declared) - (1 if gold is not None else 0)
    return (
        case,
        ignored_assertions
        + len(
            row.keys() - {"testCase", "response", "testIdx", "promptIdx", "id", "score", "success"}
        ),
        asserted,
    )


def prepare_import(raw: bytes, profile: ImportProfile) -> PreparedImport:
    if not 0 < len(raw) <= MAX_BYTES:
        raise SourceImportError("IMPORT_REQUIRES_ONE_TO_ONE_MIB_BYTES")
    if profile not in PROFILES:
        raise SourceImportError("IMPORT_PROFILE_UNSUPPORTED")
    try:
        text = raw.decode("utf-8-sig")
    except UnicodeError:
        raise SourceImportError("UTF8_IMPORT_REQUIRED") from None
    if profile == "cutback-jsonl.v1":
        rows = [_json(line) for line in text.splitlines() if line.strip()]
    elif profile == "promptfoo-0.125.1-results.v3":
        body = _json(text)
        if (
            not isinstance(body, dict)
            or not isinstance(body.get("results"), dict)
            or body["results"].get("version") != 3
        ):
            raise SourceImportError("PROMPTFOO_RESULTS_VERSION_THREE_REQUIRED")
        rows = body["results"].get("results")
    else:
        body = _json(text)
        if (
            not isinstance(body, dict)
            or not isinstance(body.get("resourceSpans"), list)
            or len(body["resourceSpans"]) > 20
        ):
            raise SourceImportError("OTLP_RESOURCE_ENVELOPE_INVALID")
        rows = []
        for resource in body["resourceSpans"]:
            if (
                not isinstance(resource, dict)
                or not isinstance(resource.get("scopeSpans"), list)
                or len(resource["scopeSpans"]) > 20
            ):
                raise SourceImportError("OTLP_SCOPE_ENVELOPE_INVALID")
            for scope in resource["scopeSpans"]:
                if (
                    not isinstance(scope, dict)
                    or not isinstance(scope.get("spans"), list)
                    or len(scope["spans"]) > 200
                ):
                    raise SourceImportError("OTLP_SPAN_ENVELOPE_INVALID")
                rows.extend(scope["spans"])
        if len(rows) > 200:
            raise SourceImportError("OTLP_IMPORT_EXCEEDS_200_SPANS")
    if not isinstance(rows, list) or not 1 <= len(rows) <= 10000:
        raise SourceImportError("IMPORT_REQUIRES_ONE_TO_TEN_THOUSAND_ROWS")
    cases, rejected, assertions = [], [], []
    projected, identifiers = 0, set()
    for i, row in enumerate(rows):
        try:
            if profile == "cutback-jsonl.v1":
                case, ignored, assertion = Case.model_validate(_ordinary_json(row)), 0, None
            elif profile == "openinference-otlp-json.v1":
                case, ignored, assertion = _openinference(row)
            else:
                case, ignored, assertion = _promptfoo(row)
            if case.id in identifiers:
                raise SourceImportError("DUPLICATE_SOURCE_CASE_IDENTITY")
            identifiers.add(case.id)
            cases.append(case)
            projected += ignored
            if assertion:
                assertions.append(assertion)
        except SourceImportError as exc:
            rejected.append({"row": i, "code": str(exc)})
        except ValidationError:
            rejected.append({"row": i, "code": "CASE_FIELDS_OR_BOUNDS_INVALID"})
        except (ValueError, TypeError, KeyError):
            rejected.append({"row": i, "code": "ROW_NOT_COMPATIBLE_WITH_SELECTED_PROFILE"})
    return PreparedImport(
        profile, hashlib.sha256(raw).hexdigest(), cases, rejected, len(rows), projected, assertions
    )


def preview_file(path: Path, profile: ImportProfile):
    if path.is_symlink() or not path.is_file() or path.stat().st_size > MAX_BYTES:
        raise SourceImportError("IMPORT_FILE_UNSAFE_OR_TOO_LARGE")
    with path.open("rb") as source:
        raw = source.read(MAX_BYTES + 1)
    return prepare_import(raw, profile)
